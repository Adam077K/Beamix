#!/usr/bin/env node
'use strict';

/**
 * setup-git-hooks.js — worktree-scoped git hooks installer
 *
 * Beamix runs 50+ concurrent `git worktree`s that share one common .git
 * directory. Writing `core.hooksPath` WITHOUT a --worktree scope flag lands
 * in the SHARED .git/config and silently redirects hook resolution for
 * every worktree that shares this repo — this happened once already
 * (2026-08-08 incident: an earlier attempt at this exact feature ran plain
 * `husky install`, which calls `git config core.hooksPath` unscoped).
 *
 * This script never calls `git config` without an explicit --worktree flag
 * for anything that changes hook *behavior*. It is designed around three
 * hard-learned failure modes from that prior attempt:
 *
 *   1. CI DETECTION: must not depend on `CI === 'true'` alone — Vercel sets
 *      CI=1, not CI=true. Any truthy CI-ish env var must short-circuit to a
 *      clean no-op BEFORE any git call, so this script can never fail a
 *      build container's `pnpm install`.
 *
 *   2. UNMET PREREQUISITE: `git config --worktree` silently changes meaning
 *      depending on whether `extensions.worktreeConfig=true` is already set
 *      on the repo:
 *        - if NOT set, and this worktree is one of several linked worktrees,
 *          the write HARD FAILS (git refuses; safe, loud).
 *        - if NOT set, and this happens to run in a repo with only one
 *          worktree so far (e.g. the very first `pnpm install` right after
 *          a fresh clone, before any other worktree exists), the write
 *          SILENTLY SUCCEEDS but lands directly in the shared .git/config —
 *          exactly the incident, just reached a different way. This is the
 *          dangerous case. This script self-establishes the extension
 *          FIRST, and refuses to proceed to the hooksPath write if it
 *          can't confirm the extension is on.
 *
 *   3. NO SILENT FALLBACK: after writing core.hooksPath with --worktree,
 *      reading it back with `--worktree --get` is NOT sufficient proof —
 *      that read succeeds in BOTH the correct case and the silent-fallback
 *      case described above, because when there's nothing to disambiguate
 *      scope, `--worktree` and the shared config resolve to the same file.
 *      The only reliable tell is cross-checking `--local --get`: if the
 *      shared/local scope ALSO reports our hooksPath value, the write did
 *      not land in a worktree-exclusive file. See
 *      `applyAndVerifyWorktreeScopedHooksPath` below.
 *
 * The installed hook directory lives inside this worktree's OWN git
 * directory (`git rev-parse --absolute-git-dir`, which is a distinct path
 * per linked worktree: `.git/worktrees/<name>/` vs `.git/` for the main
 * checkout) — never inside the tracked working tree, so nothing here needs
 * a .gitignore entry.
 */

const { spawnSync } = require('node:child_process');
const path = require('node:path');
const fs = require('node:fs');

const HOOKS_DIR_NAME = 'hooks-beamix';

// The only hook Beamix currently enforces via git hooks locally. CI-side
// validation (commit-lint.yml) runs `commitlint` directly on the PR's commit
// range and does not depend on this file at all — the two are independent
// enforcement points that happen to use the same commitlint config.
const COMMIT_MSG_HOOK = [
  '#!/usr/bin/env sh',
  '# Beamix commit-msg hook — generated by scripts/setup-git-hooks.js.',
  '# Do not edit this file directly, it is regenerated on every `pnpm install`.',
  '# Edit the COMMIT_MSG_HOOK template in scripts/setup-git-hooks.js instead.',
  'exec npx --no -- commitlint --edit "$1"',
  '',
].join('\n');

/**
 * Treats an env var as "CI-truthy" if it is set to anything other than an
 * empty string, "0", or "false" (case-insensitive). This intentionally
 * covers both GitHub Actions' `CI=true` and Vercel's `CI=1` conventions —
 * the prior attempt's `process.env.CI === 'true'` check missed the latter.
 */
function isTruthyEnvValue(value) {
  if (value === undefined || value === null) return false;
  const normalized = String(value).trim().toLowerCase();
  return normalized !== '' && normalized !== '0' && normalized !== 'false';
}

/**
 * Robust CI detection: any of CI, VERCEL, GITHUB_ACTIONS, or
 * CONTINUOUS_INTEGRATION being truthy counts as "we are in a CI/build
 * container" and this script must no-op cleanly (exit 0), never exit
 * non-zero and never touch git config.
 */
function isCIEnvironment(env) {
  const source = env || process.env;
  return (
    isTruthyEnvValue(source.CI) ||
    isTruthyEnvValue(source.VERCEL) ||
    isTruthyEnvValue(source.GITHUB_ACTIONS) ||
    isTruthyEnvValue(source.CONTINUOUS_INTEGRATION)
  );
}

function runGit(args, options) {
  const result = spawnSync('git', args, Object.assign({ encoding: 'utf8' }, options || {}));
  return {
    status: result.status,
    stdout: (result.stdout || '').trim(),
    stderr: (result.stderr || '').trim(),
    error: result.error,
  };
}

function getWorktreeRoot(cwd) {
  const result = runGit(['rev-parse', '--show-toplevel'], { cwd });
  if (result.status !== 0 || !result.stdout) return null;
  return result.stdout;
}

function getAbsoluteGitDir(cwd) {
  const result = runGit(['rev-parse', '--absolute-git-dir'], { cwd });
  if (result.status !== 0 || !result.stdout) return null;
  return result.stdout;
}

function getWorktreeConfigExtensionValue(cwd) {
  const result = runGit(['config', '--get', 'extensions.worktreeConfig'], { cwd });
  if (result.status !== 0) return null;
  return result.stdout;
}

/**
 * Ensures extensions.worktreeConfig=true is set BEFORE any --worktree
 * scoped config write is attempted.
 *
 * WHY THIS SPECIFIC WRITE IS SAFE TO LAND IN THE SHARED CONFIG:
 * extensions.worktreeConfig is a repo-level extension flag by git's own
 * design — it cannot be scoped per-worktree (it has to be visible before
 * any per-worktree config file is even consulted). Setting it true is
 * purely additive and idempotent: it does NOT set or change core.hooksPath
 * (or any other behavior-affecting key) for any worktree. It only *enables
 * the mechanism* that subsequently lets us write core.hooksPath with
 * --worktree scope. This is categorically different from writing
 * core.hooksPath unscoped (the 2026-08-08 incident), which redirects hook
 * resolution for every worktree sharing the repo.
 *
 * Returns { ok, alreadySet, reason? }.
 */
function establishWorktreeConfigExtension(cwd) {
  const current = getWorktreeConfigExtensionValue(cwd);
  if (current === 'true') {
    return { ok: true, alreadySet: true };
  }

  const writeResult = runGit(['config', 'extensions.worktreeConfig', 'true'], { cwd });
  // Re-read regardless of the write's own exit code: a concurrent worktree's
  // `pnpm install` could race to set this same idempotent flag at the same
  // time. What matters is the converged final state, not which process's
  // write call "won".
  const after = getWorktreeConfigExtensionValue(cwd);
  if (after === 'true') {
    return { ok: true, alreadySet: false };
  }

  return {
    ok: false,
    alreadySet: false,
    reason:
      'could not establish extensions.worktreeConfig=true ' +
      `(write exit ${writeResult.status}, stderr: ${writeResult.stderr || '(none)'})`,
  };
}

function writeHookFiles(hooksDir) {
  fs.mkdirSync(hooksDir, { recursive: true });
  const commitMsgPath = path.join(hooksDir, 'commit-msg');
  fs.writeFileSync(commitMsgPath, COMMIT_MSG_HOOK, { mode: 0o755 });
  // writeFileSync's `mode` is only applied when the file is newly created;
  // force the executable bit on every run in case the file already existed
  // (e.g. re-install after a permissions change).
  fs.chmodSync(commitMsgPath, 0o755);
  return commitMsgPath;
}

/**
 * Writes core.hooksPath scoped to THIS worktree only, then hardens the
 * verification beyond "is it readable".
 *
 * Reading back via `git config --worktree --get` is NOT sufficient proof of
 * correct scoping: that read succeeds identically whether the value landed
 * in the worktree-exclusive config.worktree file (correct) OR silently fell
 * back into the shared config (the dangerous case — see module docstring,
 * failure mode 2). The only reliable tell is cross-checking `--local`: for
 * a linked worktree, `--local` resolves to the shared/common config file.
 * If that ALSO reports our hooksPath value, the write did not land in a
 * worktree-exclusive file and must be treated as a failure, loudly.
 */
function applyAndVerifyWorktreeScopedHooksPath(cwd, hooksDir) {
  const writeResult = runGit(['config', '--worktree', 'core.hooksPath', hooksDir], { cwd });
  if (writeResult.status !== 0) {
    return {
      ok: false,
      reason:
        `git config --worktree core.hooksPath failed (exit ${writeResult.status}): ` +
        `${writeResult.stderr || '(no stderr)'}`,
    };
  }

  const worktreeRead = runGit(['config', '--worktree', '--get', 'core.hooksPath'], { cwd });
  if (worktreeRead.status !== 0 || worktreeRead.stdout !== hooksDir) {
    return {
      ok: false,
      reason:
        'core.hooksPath did not read back correctly from worktree scope ' +
        `(got: ${worktreeRead.stdout || '(empty)'})`,
    };
  }

  const localRead = runGit(['config', '--local', '--get', 'core.hooksPath'], { cwd });
  if (localRead.status === 0 && localRead.stdout === hooksDir) {
    return {
      ok: false,
      reason:
        `SHARED-SCOPE FALLBACK DETECTED: core.hooksPath=${hooksDir} is visible via ` +
        "'git config --local --get', meaning the --worktree write silently landed in " +
        'the shared repo config instead of this worktree\'s config.worktree file. ' +
        'This would affect every worktree that shares this repo. Refusing to proceed.',
    };
  }

  return { ok: true };
}

function main() {
  // CI detection MUST be the very first thing evaluated, using only env var
  // reads (no subprocess calls that could themselves fail). A build
  // container's `pnpm install` must never be failed by this script.
  if (isCIEnvironment()) {
    process.stdout.write(
      'setup-git-hooks: CI environment detected — skipping local hook install ' +
        '(CI-side validation runs commitlint directly; see .github/workflows/commit-lint.yml).\n',
    );
    process.exit(0);
    return;
  }

  if (process.env.HUSKY === '0') {
    process.stdout.write('setup-git-hooks: HUSKY=0 — skipping hook install.\n');
    process.exit(0);
    return;
  }

  const cwd = process.cwd();

  const worktreeRoot = getWorktreeRoot(cwd);
  if (!worktreeRoot) {
    // Not inside a git working tree at all (e.g. installing from a packed
    // tarball, or a Docker build stage with no .git present). Hook
    // installation is meaningless here — this is not an error condition.
    process.stderr.write(
      'setup-git-hooks: not inside a git working tree — skipping hook install.\n',
    );
    process.exit(0);
    return;
  }

  const gitDir = getAbsoluteGitDir(cwd);
  if (!gitDir) {
    process.stderr.write(
      'setup-git-hooks: could not resolve git dir via `git rev-parse --absolute-git-dir` — skipping.\n',
    );
    process.exit(0);
    return;
  }

  const establish = establishWorktreeConfigExtension(worktreeRoot);
  if (!establish.ok) {
    process.stderr.write(`setup-git-hooks: FAIL — ${establish.reason}\n`);
    process.stderr.write(
      'setup-git-hooks: refusing to write core.hooksPath without a confirmed ' +
        'worktree-scoped config extension (this guards against the 2026-08-08 ' +
        'shared-config incident).\n',
    );
    process.exit(1);
    return;
  }

  const hooksDir = path.join(gitDir, HOOKS_DIR_NAME);
  writeHookFiles(hooksDir);

  const verify = applyAndVerifyWorktreeScopedHooksPath(worktreeRoot, hooksDir);
  if (!verify.ok) {
    process.stderr.write(`setup-git-hooks: FAIL — ${verify.reason}\n`);
    process.exit(1);
    return;
  }

  process.stdout.write('setup-git-hooks: hooks installed for this worktree only.\n');
  process.stdout.write(`  worktree:  ${worktreeRoot}\n`);
  process.stdout.write(
    `  hooksPath: ${hooksDir}` +
      (establish.alreadySet ? '' : ' (extensions.worktreeConfig newly established)') +
      '\n',
  );
}

if (require.main === module) {
  main();
}

module.exports = {
  HOOKS_DIR_NAME,
  COMMIT_MSG_HOOK,
  isTruthyEnvValue,
  isCIEnvironment,
  runGit,
  getWorktreeRoot,
  getAbsoluteGitDir,
  getWorktreeConfigExtensionValue,
  establishWorktreeConfigExtension,
  writeHookFiles,
  applyAndVerifyWorktreeScopedHooksPath,
  main,
};
